#!/usr/bin/env python3
"""Build the static site from src/index.html.

    python3 build.py

Writes:
  dist/index.html      English page (default, at /)
  dist/hi/index.html   Hindi page (at /hi/)
  dist/sitemap.xml, dist/robots.txt, dist/_headers

Every visible string lives once in src/index.html as a pair:
  data-en="..." data-hi="..."            -> element text
  data-alt-en / data-alt-hi              -> alt=""
  data-aria-en / data-aria-hi            -> aria-label=""
  data-advice-en / data-advice-hi        -> data-advice="" (visit guide)
  data-tpl-en / data-tpl-hi              -> data-tpl=""    (filter status, live clock)
  data-play-en|pause-en / -hi            -> data-play / data-pause (slideshow button)
The build writes the chosen language straight into the HTML, so the pages are
complete without JavaScript and each language can be found by search engines.

Standard library only. Change SITE_URL when the site moves to its own domain.
"""
