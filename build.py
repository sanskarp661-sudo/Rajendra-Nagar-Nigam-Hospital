def url(lang):
    return f"{SITE_URL}/{LANGS[lang]['path']}"


def head_links(lang):
    c = LANGS[lang]
    other = LANGS[c["alt"]]
    tags = [
        f'<link rel="canonical" href="{url(lang)}">',
        f'<link rel="alternate" hreflang="en" href="{url("en")}">',
        f'<link rel="alternate" hreflang="hi" href="{url("hi")}">',
        f'<link rel="alternate" hreflang="x-default" href="{url("en")}">',
        '<meta property="og:type" content="website">',
        f'<meta property="og:site_name" content="{html.escape(c["name"])}">',
        f'<meta property="og:title" content="{html.escape(c["title"])}">',
        f'<meta property="og:description" content="{html.escape(c["desc"])}">',
        f'<meta property="og:url" content="{url(lang)}">',
        f'<meta property="og:locale" content="{c["locale"]}">',
        f'<meta property="og:locale:alternate" content="{other["locale"]}">',
        f'<meta property="og:image" content="{SITE_URL}/assets/og-image.jpg">',
        '<meta property="og:image:width" content="1200">',
        '<meta property="og:image:height" content="630">',
        '<meta name="twitter:card" content="summary_large_image">',
    ]
    return "\n".join(tags)


